import { QUEEN_DETAILED } from './queen-landmarks.mod.js';

function buildQueenBuildings(world) {
    const { THREE, scene } = world;
    const groundAt = world.groundAt || (() => 0);

    function hash(s) {
        let h = 2166136261;
        for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
        return (h >>> 0) / 4294967295;
    }
    const srgb = (hex) => new THREE.Color(hex).convertSRGBToLinear();

    // muted, weathered palette families keyed by OSM building use
    const FAM = {
        retail:       ['#b9b0a2', '#c4b6a3', '#a89f92', '#c9bfa8'],
        commercial:   ['#9fa6ac', '#b0b3b0', '#8f9aa2', '#a7a49b'],
        office:       ['#94a1ab', '#a6b0b4', '#8a949c', '#9ba7ad'],
        apartments:   ['#b4a596', '#a7aeb2', '#c1b3a0', '#9ea89e'],
        hotel:        ['#b0a494', '#bcae9a', '#a29a8b'],
        civic:        ['#cdbfa4', '#d3c6ad', '#c2b596'],
        university:   ['#c3b7a0', '#b6ab97'],
        train_station:['#c8bba1'],
        construction: ['#9a968c'],
        kiosk:        ['#8f8a80'],
        service:      ['#8f8a80'],
        container:    ['#7d8a86'],
        ruins:        ['#b7ab95'],
        yes:          ['#b3a998', '#b8afa0', '#a9a292', '#c0b6a4'],
    };
    const toneFor = (use, id) => {
        const fam = FAM[use] || FAM.yes;
        return fam[Math.floor(hash(id) * fam.length)];
    };

    // signed area in XZ — used to force a consistent winding for outward walls
    const ringArea = (pts) => {
        let a = 0;
        for (let i = 0; i < pts.length - 1; i++) a += pts[i][0] * pts[i + 1][1] - pts[i + 1][0] * pts[i][1];
        return a / 2;
    };

    // one building's walls + flat roof cap into the shared vertex-colour bucket
    function addBuilding(bucket, ring0, base, top, cUp, cBase, bandY) {
        let r = ring0.slice();
        if (r.length > 1 && r[0][0] === r[r.length - 1][0] && r[0][1] === r[r.length - 1][1]) r = r.slice(0, -1);
        if (r.length < 3) return;
        if (ringArea(r) < 0) r.reverse();   // CCW in XZ → walls wind outward-facing

        const P = bucket.pos, C = bucket.col;
        const v = (x, y, z, c) => { P.push(x, y, z); C.push(c.r, c.g, c.b); };
        const quad = (ax, az, bx, bz, y0, y1, c) => {
            // outside face of edge a→b, CCW ring: normal points to the right of a→b
            v(ax, y0, az, c); v(bx, y0, bz, c); v(bx, y1, bz, c);
            v(ax, y0, az, c); v(bx, y1, bz, c); v(ax, y1, az, c);
        };

        // a shopfront base band, the main wall, and a darker cornice band at the
        // top — three horizontal courses read as a building, not a plain block.
        const corniceH = Math.min(1.3, Math.max(0.6, (top - base) * 0.06));
        const corniceY = Math.max(bandY, top - corniceH);
        const cCornice = cUp.clone().multiplyScalar(0.7);
        for (let i = 0; i < r.length; i++) {
            const a = r[i], b = r[(i + 1) % r.length];
            const bandTop = Math.min(bandY, top);
            quad(a[0], a[1], b[0], b[1], base, bandTop, cBase);
            if (corniceY > bandY) quad(a[0], a[1], b[0], b[1], bandY, corniceY, cUp);
            if (top > corniceY) quad(a[0], a[1], b[0], b[1], corniceY, top, cCornice);
        }

        // flat roof cap — centroid fan, wound so it faces up (+y)
        let cx = 0, cz = 0; for (const p of r) { cx += p[0]; cz += p[1]; } cx /= r.length; cz /= r.length;
        for (let i = 0; i < r.length; i++) {
            const a = r[i], b = r[(i + 1) % r.length];
            v(cx, top, cz, cUp); v(b[0], top, b[1], cUp); v(a[0], top, a[1], cUp);
        }
    }

    const bucket = { pos: [], col: [] };
    let n = 0;
    for (const line of BLDG.split('\n')) {
        if (!line) continue;
        const b1 = line.indexOf('|'), b2 = line.indexOf('|', b1 + 1), b3 = line.indexOf('|', b2 + 1), b4 = line.indexOf('|', b3 + 1);
        const id = line.slice(0, b1);
        if (QUEEN_DETAILED.has(id)) continue;   // built in detail by queen-landmarks.mod.js
        const use = line.slice(b2 + 1, b3);
        const h = parseFloat(line.slice(b3 + 1, b4)) || 14;
        const ring = line.slice(b4 + 1).split(' ').map((p) => { const c = p.indexOf(','); return [+p.slice(0, c), +p.slice(c + 1)]; });
        let gmin = Infinity;
        for (const [x, z] of ring) gmin = Math.min(gmin, groundAt(x, z));
        if (!isFinite(gmin)) gmin = 0;
        const base = gmin - 0.5;               // sink slightly: no gap on the slope
        const top = base + h;
        const cUp = srgb(toneFor(use, id));
        const cBase = cUp.clone().multiplyScalar(0.6);
        const bandY = base + Math.min(5.5, h * 0.32);
        addBuilding(bucket, ring, base, top, cUp, cBase, bandY);
        n++;
    }

    const geo = new THREE.BufferGeometry();
    geo.setAttribute('position', new THREE.BufferAttribute(new Float32Array(bucket.pos), 3));
    geo.setAttribute('color', new THREE.BufferAttribute(new Float32Array(bucket.col), 3));
    geo.computeVertexNormals();
    const mesh = new THREE.Mesh(geo, new THREE.MeshStandardMaterial({ vertexColors: true, roughness: 0.82, metalness: 0, side: THREE.DoubleSide }));
    mesh.name = 'queen_buildings_massing';
    scene.add(mesh);
    world.part('queen_buildings_00', mesh);

    return { count: n, tris: bucket.pos.length / 9 };
}

export { buildQueenBuildings };
